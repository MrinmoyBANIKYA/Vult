#!/usr/bin/env node
/**
 * Builds supabase/seed.sql from the app's own demo data (src/lib/engine.js and src/lib/autopilot.js),
 * so the database and the demo mode always tell the same story.
 *
 *   npm run db:seed:generate
 *
 * IDs are derived from stable names, so re-running produces the same file. Times are written relative
 * to now() in each organisation's time zone, so "02:14 today" stays true whenever you reset the database.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { R, ALL, AG, planFor, logLines, filesFor, defaultEntry, calc, sharePx } from '../src/lib/engine.js';
import { AUTO } from '../src/lib/autopilot.js';

const OUT = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));

/* ------------------------------------------------------------------ SQL helpers */
const uuid = name => {
  const h = createHash('md5')
    .update('vult:' + name)
    .digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = v => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const json = v => `${q(JSON.stringify(v))}::jsonb`;
const textArr = a => `array[${a.map(q).join(', ')}]::text[]`;
const intArr = a => (a.length ? `array[${a.join(', ')}]::integer[]` : `'{}'::integer[]`);
const insert = (table, rows) => {
  if (!rows.length) return '';
  const cols = Object.keys(rows[0]);
  const values = rows.map(r => '  (' + cols.map(c => r[c]).join(', ') + ')').join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values};\n`;
};

/* ------------------------------------------------------------------ time labels -> SQL timestamps */
const DOW = { Mon: 1, Tue: 2, Wed: 3, Thu: 4, Fri: 5, Sat: 6, Sun: 7 };
const MON = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6, Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12 };
function ts(label, tz, direction = 'past') {
  const local = `(now() at time zone ${q(tz)})`;
  const at = (dayExpr, hhmm) => `((date_trunc('day', ${local}) ${dayExpr} + time ${q(hhmm)}) at time zone ${q(tz)})`;
  const s = String(label || '').trim();
  let m;
  if (!s || /^just now$/i.test(s)) return 'now()';
  if ((m = /^(\d+)m$/.exec(s))) return `now() - interval '${m[1]} minutes'`;
  if ((m = /^(\d+)h$/.exec(s))) return `now() - interval '${m[1]} hours'`;
  if ((m = /^(\d\d:\d\d)$/.exec(s))) {
    const today = at('', m[1]);
    // "06:31" in the past tense means the most recent 06:31, which is yesterday's before that time of day.
    return direction === 'past'
      ? `(case when ${today} > now() then ${today} - interval '1 day' else ${today} end)`
      : today;
  }
  if ((m = /^Yesterday(?: (\d\d:\d\d))?$/.exec(s))) return at("- interval '1 day'", m[1] || '12:00');
  if ((m = /^(Mon|Tue|Wed|Thu|Fri|Sat|Sun)(?: (\d\d:\d\d))?/.exec(s))) {
    const dow = `extract(isodow from ${local})::int`;
    const days =
      direction === 'future' ? `(((${DOW[m[1]]} - ${dow} + 6) % 7) + 1)` : `(((${dow} - ${DOW[m[1]]} + 6) % 7) + 1)`;
    return at(`${direction === 'future' ? '+' : '-'} ${days} * interval '1 day'`, m[2] || '12:00');
  }
  if ((m = /^(\d{1,2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)$/.exec(s)))
    return `((make_date(extract(year from ${local})::int, ${MON[m[2]]}, ${m[1]}) + time '12:00') at time zone ${q(tz)})`;
  throw new Error(`Unknown time label: "${s}"`);
}

const STATUS = { run: 'running', rev: 'in_review', ok: 'delivered', draft: 'draft', paused: 'paused' };
const SLUG = { uk: 'carrow-partners', us: 'hollis-street-capital' };

/* ------------------------------------------------------------------ build */
const out = [
  '-- =============================================================================================',
  '-- Vult demo data. Generated by scripts/generate-seed.mjs from src/lib/engine.js and',
  '-- src/lib/autopilot.js; edit those and run `npm run db:seed:generate` rather than this file.',
  '-- Every company, client and figure is fictional.',
  '-- =============================================================================================',
  '',
  '-- Local development lets any new account join the demo workspaces. A client project leaves this off.',
  "insert into public.app_settings (key, value) values ('allow_demo_join', 'true'::jsonb)",
  '  on conflict (key) do update set value = excluded.value;',
  ''
];

for (const k of ['uk', 'us']) {
  const d = R[k],
    A = AUTO[k],
    tz = d.tz;
  const org = uuid(`org:${k}`),
    company = uuid(`company:${k}`),
    flagship = uuid(`engagement:${k}:main`),
    run = uuid(`run:${k}:${d.runNo}`);
  const plan = planFor(new Set(ALL), k, false);
  const currency = k === 'uk' ? 'GBP' : 'USD';
  const engId = name => (name === d.project ? flagship : uuid(`engagement:${k}:${name}`));

  out.push(`-- ${d.org} (${d.orgDesc})`);
  out.push(
    insert('organizations', [
      {
        id: q(org),
        slug: q(SLUG[k]),
        name: q(d.org),
        mono: q(d.orgMono),
        description: q(d.orgDesc),
        region: q(k),
        city: q(d.city),
        timezone: q(tz),
        office_code: q(d.office),
        currency: q(currency),
        accounting_standard: q(d.gaap),
        plan: q('deal_team'),
        packs_included: 25,
        packs_used: 18,
        renews_on: `(date_trunc('month', now()) + interval '1 month')::date`,
        is_demo: 'true'
      }
    ])
  );

  out.push(
    insert('companies', [
      {
        id: q(company),
        org_id: q(org),
        name: q(d.target),
        ticker: q(d.ticker),
        exchange: q(d.exch),
        sector: q(d.sector),
        currency: q(currency),
        share_price: q(d.price),
        price_in_pence: q(Boolean(d.pence)),
        shares_m: q(d.shares),
        net_debt_m: q(d.netDebt)
      }
    ])
  );

  const engagements = [
    {
      id: q(flagship),
      org_id: q(org),
      company_id: q(company),
      code: q(d.code),
      name: q(d.project),
      target_label: q(d.target),
      type: q(d.type),
      status: q('delivered'),
      progress: 100,
      owner_name: q(d.me.n),
      reviewer_name: q(d.reviewer),
      house_style: q(d.style),
      data_room: q(d.vdr),
      accounting_basis: q(`${d.gaap}, ${d.fy}`),
      is_flagship: 'true',
      created_at: `now() - interval '2 days'`,
      updated_at: `now() - interval '23 minutes'`
    },
    ...d.engagements.slice(1).map(e => ({
      id: q(engId(e.n)),
      org_id: q(org),
      company_id: 'null',
      code: 'null',
      name: q(e.n),
      target_label: q(e.t),
      type: q(e.ty),
      status: q(STATUS[e.s]),
      progress: e.s === 'run' ? e.p : e.s === 'ok' || e.s === 'rev' ? 100 : 0,
      owner_name: q(e.o),
      reviewer_name: q(d.reviewer),
      house_style: q(d.style),
      data_room: 'null',
      accounting_basis: q(d.gaap),
      is_flagship: 'false',
      created_at: `now() - interval '9 days'`,
      updated_at: ts(e.u, tz)
    }))
  ];
  out.push(insert('engagements', engagements));

  // The flagship's delivered run, its log, files and hallmark
  const minutes = plan.total;
  out.push(
    insert('runs', [
      {
        id: q(run),
        org_id: q(org),
        engagement_id: q(flagship),
        run_no: d.runNo,
        status: q('delivered'),
        priority: 'false',
        deliverables: textArr(ALL),
        plan: json({ total: plan.total, stages: plan.st, outputs: plan.outs, price: plan.price, packed: plan.packed }),
        price: q(plan.price),
        currency: q(currency),
        minutes_planned: minutes,
        started_at: `now() - interval '${23 + minutes} minutes'`,
        delivered_at: `now() - interval '23 minutes'`
      }
    ])
  );
  out.push(
    insert(
      'run_events',
      logLines(plan, d).map(l => ({
        org_id: q(org),
        run_id: q(run),
        at_minute: q(Math.round(l.t * 100) / 100),
        agent: q((AG[l.tag] && AG[l.tag].n) || l.tag),
        message: q(l.x),
        created_at: `now() - interval '${(23 + minutes - l.t).toFixed(2)} minutes'`
      }))
    )
  );
  out.push(
    insert(
      'files',
      filesFor(plan, d).map(([kind, name, meta, size]) => ({
        id: q(uuid(`file:${k}:${name}`)),
        org_id: q(org),
        engagement_id: q(flagship),
        run_id: q(run),
        kind: q(kind),
        name: q(name),
        description: q(meta),
        size_label: q(size),
        storage_path: q(`${org}/${flagship}/${name}`)
      }))
    )
  );
  out.push(
    insert('hallmarks', [
      {
        run_id: q(run),
        org_id: q(org),
        engagement_id: q(flagship),
        fineness: 999,
        office_code: q(d.office),
        signed_by_name: q(d.reviewer),
        signed_initials: q(d.init),
        checks_passed: 412,
        checks_total: 412,
        figures_traced: 3184,
        figures_total: 3187,
        signed_at: `now() - interval '23 minutes'`
      }
    ])
  );
  const entry = defaultEntry(d);
  out.push(
    insert('model_versions', [
      {
        id: q(uuid(`model:${k}:3`)),
        org_id: q(org),
        engagement_id: q(flagship),
        version: 3,
        scenario: q('base'),
        wacc: q(d.wacc),
        terminal_growth: q(d.tgr),
        senior_leverage: 5,
        entry_multiple: q(entry),
        exit_multiple: q(entry),
        note: q(`Reviewed by ${d.reviewer}`),
        created_at: `now() - interval '23 minutes'`
      }
    ])
  );

  // Sources and the evidence trail
  out.push(
    insert(
      'documents',
      d.docs.map(doc => ({
        id: q(uuid(`doc:${k}:${doc.id}`)),
        org_id: q(org),
        engagement_id: q(flagship),
        slug: q(doc.id),
        title: q(doc.t),
        publisher: q(doc.who),
        doc_type: q(doc.ty),
        format: q(doc.f),
        source: q(doc.src),
        published_label: q(doc.date),
        pages_label: q(doc.pages),
        cited_count: doc.cited
      }))
    )
  );
  const docIds = new Set(d.docs.map(doc => doc.id));
  out.push(
    insert(
      'evidence',
      Object.entries(d.ev).map(([key, e]) => {
        const slug = e.pg.split('.')[0],
          page = d.pages[e.pg];
        return {
          id: q(uuid(`ev:${k}:${key}`)),
          org_id: q(org),
          engagement_id: q(flagship),
          key: q(key),
          label: q(e.l),
          value: q(e.v),
          document_id: docIds.has(slug) ? q(uuid(`doc:${k}:${slug}`)) : 'null',
          page_ref: q(page ? (typeof page.p === 'number' ? `p.${page.p}` : page.p) : null),
          highlight_rows: intArr(e.hl || []),
          extract: q(e.ex),
          normalisation: q(e.norm || null),
          reconciliation: q(e.rec || null),
          used_in: json(e.used || [])
        };
      })
    )
  );

  // IC memo comments, each with the co-pilot's reply
  const down = sharePx(d, calc(d, 'downside', d.wacc, d.tgr).vps);
  const comments = [];
  d.comments.forEach(c => {
    const id = uuid(`comment:${k}:${c.id}`);
    comments.push({
      id: q(id),
      org_id: q(org),
      engagement_id: q(flagship),
      anchor: q('memo'),
      parent_id: 'null',
      author_id: 'null',
      author_name: q(c.who),
      author_title: q(c.role),
      body: q(c.text),
      created_at: ts(c.ago, tz)
    });
    if (c.reply)
      comments.push({
        id: q(uuid(`comment:${k}:${c.id}:reply`)),
        org_id: q(org),
        engagement_id: q(flagship),
        anchor: q('memo'),
        parent_id: q(id),
        author_id: 'null',
        author_name: q('Vult'),
        author_title: q('Co-pilot'),
        body: q(c.reply.replace('{down}', down)),
        created_at: ts(c.ago, tz) + ` + interval '1 minute'`
      });
  });
  out.push(insert('comments', comments));

  // Autopilot
  out.push(
    insert(
      'approvals',
      A.approvals.map(a => ({
        id: q(uuid(`approval:${k}:${a.id}`)),
        org_id: q(org),
        engagement_id: d.engagements.some(e => e.n === a.eng) || a.eng === d.project ? q(engId(a.eng)) : 'null',
        kind: q(a.kind),
        agent: q(a.who),
        title: q(a.title),
        why: q(a.why),
        diff: json(a.diff),
        status: q('pending'),
        created_at: ts(a.age, tz)
      }))
    )
  );
  out.push(
    insert(
      'monitors',
      A.monitors.map((x, i) => ({
        id: q(uuid(`monitor:${k}:${x.id}`)),
        org_id: q(org),
        name: q(x.n),
        scope: q(x.scope),
        trigger_label: q(x.trig),
        schedule_label: q(x.next),
        enabled: q(x.on),
        runs_count: x.runs,
        last_run_at: ts(x.last, tz),
        position: i
      }))
    )
  );
  out.push(
    insert(
      'brief_items',
      A.brief.map((b, i) => ({
        id: q(uuid(`brief:${k}:${b.id}`)),
        org_id: q(org),
        kind: q(b.kind),
        tone: q(b.tone || 'info'),
        agent: q(b.agent),
        title: q(b.title),
        body: q(b.body),
        impact: q(b.impact),
        action: json({ label: b.act[0], view: b.act[1], tab: b.act[2] || null }),
        occurred_at: ts(b.when, tz, b.kind === 'earnings' ? 'future' : 'past'),
        position: i
      }))
    )
  );
  out.push(
    insert(
      'activity_log',
      A.log.map(([when, agent, message]) => ({
        org_id: q(org),
        agent: q(agent),
        message: q(message),
        occurred_at: ts(when, tz)
      }))
    )
  );
}

writeFileSync(OUT, out.join('\n'));
console.log(`Wrote ${OUT}`);
